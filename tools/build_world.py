def city_to(name):
    pre = 'во' if name.startswith(('Влад',)) else 'в'
    if name == 'Санкт-Петербург':
        return 'в Петербург'
    if name.endswith('а') and ' ' not in name:
        return f'{pre} {name[:-1]}у'
    return f'{pre} {name}'

def city_type(name, pop):
    if name in ('Москва', 'Санкт-Петербург'):
        return 'capital'
    if pop >= 1_000_000:
        return 'million'
    if pop >= 300_000:
        return 'large'
    if pop >= 100_000:
        return 'medium'
    return 'small'

