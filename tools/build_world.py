def build_names():
    rows = list(csv.DictReader(open(os.path.join(DATA, 'names_mercator_1975_2007.csv'), encoding='utf-8')))
    by = defaultdict(dict)
    for r in rows:
        y = int(r['year'])
        sex = 'm' if r['sex'] == 'М' else 'f'
        by[(y, sex)][nice(r['name'])] = int(r['num'])
    ru = {}
    for y in range(1980, 2008):
        ru[y] = {s: by[(y, s)] for s in 'mf'}
    # 2008–2012: у names.mercator.ru данных нет. Берём 2007 год и сдвигаем веса по трендам
    # из рейтингов ЗАГС 2010-х (рост Софии, Алисы, Варвары, Евы, Матвея, Тимофея, Марка, Льва;
    # спад Анастасии, Никиты, Дмитрия). Это оценка, а не точные данные.
    trend = {'f': {'София': 1.25, 'Софья': 1.1, 'Алиса': 1.2, 'Варвара': 1.2, 'Ева': 1.25, 'Ульяна': 1.12,
                   'Милана': 1.25, 'Анастасия': 0.93, 'Екатерина': 0.96, 'Юлия': 0.92},
             'm': {'Матвей': 1.18, 'Тимофей': 1.15, 'Марк': 1.2, 'Лев': 1.25, 'Фёдор': 1.12, 'Артём': 1.05,
                   'Михаил': 1.06, 'Никита': 0.94, 'Дмитрий': 0.96, 'Андрей': 0.95}}
    seed = {'f': {'София': 600, 'Ева': 300, 'Милана': 250}, 'm': {'Марк': 400, 'Лев': 250}}
    prev = ru[2007]
    for y in range(2008, 2013):
        cur = {}
        for s in 'mf':
            d = dict(prev[s])
            for n, v in seed[s].items():
                d.setdefault(n, v)
            for n in list(d):
                d[n] = round(d[n] * trend[s].get(n, 1.0))
            cur[s] = d
        ru[y] = cur
        prev = cur
    # Оставляем топ-50 каждого пола: вместе это топ-100 года.
    for y in ru:
        for s in 'mf':
            ru[y][s] = dict(sorted(ru[y][s].items(), key=lambda kv: -kv[1])[:50])
    json.dump({'_about': 'Имена. ru — топ-100 имён каждого года рождения (50 мужских и 50 женских) с частотами: '
               '1980–2007 по данным names.mercator.ru (Москва и область), 2008–2012 — оценка по трендам ЗАГС. '
               'Национальные пулы — распространённые имена по региональным рейтингам, без редких; '
               'old — для родившихся до 2000 года, new — после. Собрано скриптом tools/build_world.py.',
               'ru': ru, 'ethnic': ETHNIC},
              open(os.path.join(OUT, 'names.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    return ru


