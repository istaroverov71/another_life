def region_loc(short, given):
    if given:
        return given
    words = short.split()
    adj, noun = words[0], words[-1]
    if noun == 'область':
        return f'в {adj[:-2]}ой области'
    if noun == 'край':
        return f'в {adj[:-2]}ом крае'
    raise ValueError(short)

