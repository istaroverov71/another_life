def interpolate(series, years):
    known = sorted((int(y), v) for y, v in series.items() if v is not None)
    res = {}
    for y in years:
        lo = max((k for k in known if k[0] <= y), default=None)
        hi = min((k for k in known if k[0] >= y), default=None)
        if lo is None:
            res[y] = hi[1]
        elif hi is None:
            res[y] = lo[1]
        elif lo[0] == hi[0]:
            res[y] = lo[1]
        else:
            res[y] = lo[1] + (hi[1] - lo[1]) * (y - lo[0]) / (hi[0] - lo[0])
    return res


def build_regions():
    ros = json.load(open(os.path.join(DATA, 'rosstat_regions.json'), encoding='utf-8'))
    births = ros['tabR0125']['data']
    popul = ros['tabR0101']['data']
    le_m = ros['tabR0154']['data']
    le_f = ros['tabR0155']['data']
    years = list(range(1980, 2013))
    b = {short: dict(births[full]) for short, (full, _, _) in REGIONS.items()}
    # Тюменская и Архангельская области у Росстата включают свои автономные округа.
    for parent, kids in (('Тюменская область', ['Ханты-Мансийский АО', 'Ямало-Ненецкий АО']),
                         ('Архангельская область', ['Ненецкий АО'])):
        for y, v in b[parent].items():
            if v is not None:
                b[parent][y] = v - sum(b[k][y] or 0 for k in kids)
    # До 1992 года Чечня и Ингушетия считались вместе. Делим по соотношению 2005 года.
    share = births['Республика Ингушетия']['2005'] / (births['Республика Ингушетия']['2005'] + births['Чеченская Республика']['2005'])
    for y in ('1980', '1985', '1990'):
        total = b['Чечня'][y]
        b['Ингушетия'][y] = total * share
        b['Чечня'][y] = total * (1 - share)

    cities = json.load(open(os.path.join(DATA, 'cities_wiki.json'), encoding='utf-8'))
    pgt = json.load(open(os.path.join(DATA, 'pgt_wiki.json'), encoding='utf-8'))
    out = []
    for short, (full, loc, mix) in REGIONS.items():
        rc = [c for c in cities if c['region'] == short]
        rp = [p for p in pgt if p['region'] == short and (p['pop'] or 0) >= 2000]
        pop_now = (popul[full].get('2020') or popul[full].get('2024')) * 1000
        if short == 'Тюменская область':
            pop_now -= (popul['Ханты-Мансийский автономный округ - Югра']['2020'] + popul['Ямало-Ненецкий автономный округ']['2020']) * 1000
        if short == 'Архангельская область':
            pop_now -= popul['Ненецкий автономный округ']['2020'] * 1000
        city_pop = sum(c['pop'] for c in rc)
        rural = max(pop_now - city_pop, 0)
        names = {'ru': round(1 - sum(mix.values()), 3), **mix}
        out.append({
            'id': short,
            'in': region_loc(short, loc),
            'births': {y: round(v) for y, v in interpolate(b[short], years).items()},
            'life_expectancy': {'m': le_m[full].get('2023'), 'f': le_f[full].get('2023')},
            'names': names,
            'village_word': VILLAGE_WORD[short],
            'rural_weight': rural,
            'cities': [{
                'name': c['name'], 'pop': c['pop'], 'type': city_type(c['name'], c['pop']),
                'in': CITY_IN.get(c['name'], f"в городе {c['name']}"),
                **({'to': city_to(c['name'])} if c['name'] in CITY_IN else {}),
            } for c in sorted(rc, key=lambda c: -c['pop'])],
            'towns': [{'name': p['name'], 'pop': p['pop']} for p in sorted(rp, key=lambda p: -p['pop'])],
        })
    json.dump({'_about': 'Регионы России для выбора места рождения. births — число родившихся по годам '
               '(Росстат, между опорными годами линейная интерполяция). Внутри региона город выбирается '
               'пропорционально населению, сельская местность — по rural_weight (население региона минус '
               'население городов). life_expectancy — ожидаемая продолжительность жизни при рождении, 2023 год. '
               'names — доля семей с национальными именами. Собрано скриптом tools/build_world.py.',
               'regions': out}, open(os.path.join(OUT, 'regions.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    return out


