def opt(fid, extra_if=None):
    f = careers[fid]
    o = {'label': f['label'], 'result': RES[fid][0], 'results': RES[fid], 'fx': {'job': fid}}
    cond = {}
    if f.get('place'): cond['city'] = f['place']
    if extra_if: cond.update(extra_if)
    if cond: o['if'] = cond
    return o

def edu_if(fid):
    e = careers[fid]['edu']
    if 'none' in e: return None
    if e == ['uni']: return {'flags': ['uni']}
    return {'any': ['uni', 'college']}

